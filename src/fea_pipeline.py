import math
import os
import re
import subprocess
from dataclasses import dataclass
from typing import Dict, List, Tuple


@dataclass
class SimulationResult:
  mesh_size_h: float
  num_nodes: int
  num_elements: int
  max_von_mises_mpa: float
  max_displacement_mm: float
  solve_time_sec: float


class FEAPipeline:
  """Automated structural FEA pipeline using open-source tools."""

  def __init__(
      self,
      work_dir: str = "./run",
      youngs_modulus_mpa: float = 3500.0,
      poissons_ratio: float = 0.36,
      density_tonne_mm3: float = 1.24e-9,
  ):
    self.work_dir = work_dir
    self.E = youngs_modulus_mpa
    self.nu = poissons_ratio
    self.rho = density_tonne_mm3
    os.makedirs(self.work_dir, exist_ok=True)

  def generate_calculix_deck(
      self,
      mesh_inp_path: str,
      output_deck_path: str,
      force_total_n: float = 150.0,
      load_patch_area_mm2: float = 600.0,
  ) -> str:
    """Generates a unit-consistent CalculiX input deck (mm, N, MPa, tonne).

    Avoids point-load singularities by applying a surface pressure traction.
    """
    pressure_mpa = force_total_n / load_patch_area_mm2

    deck_content = f"""** CalculiX Input Deck Generated by Open-FEA Pipeline
** Author: Jacob Astorga
*INCLUDE, INPUT={os.path.basename(mesh_inp_path)}
*MATERIAL, NAME=PLA_PRINTED
*ELASTIC
{self.E:.1f}, {self.nu:.2f}
*DENSITY
{self.rho:.4e}
*SOLID SECTION, ELSET=Eall, MATERIAL=PLA_PRINTED
*STEP
*STATIC
** Boundary Condition: Fixed displacement on washer bearing surfaces
*BOUNDARY
N_BOLT_WASHERS, 1, 3, 0.0
** Distributed surface pressure on load pad (avoids point singularities)
*DLOAD
E_LOAD_PAD, P, {pressure_mpa:.4f}
*NODE FILE
U, RF
*EL FILE
S, E
*NODE PRINT, NSET=N_BOLT_WASHERS, TOTALS=ONLY
RF
*END STEP
"""
    with open(output_deck_path, "w") as f:
      f.write(deck_content)
    return output_deck_path

  def calculate_gci(
      self,
      results: List[SimulationResult],
      refinement_ratio: float = 1.414,
      safety_factor: float = 1.25,
  ) -> Dict[str, float]:
    """Computes ASME V&V 20 Grid Convergence Index (GCI) across 3 systematic mesh levels.

    results order: [fine (h1), medium (h2), coarse (h3)]
    """
    if len(results) < 3:
      raise ValueError("GCI requires at least 3 mesh refinement levels.")

    f1 = results[0].max_displacement_mm
    f2 = results[1].max_displacement_mm
    f3 = results[2].max_displacement_mm

    r = refinement_ratio

    # Apparent order of convergence p
    try:
      p = abs(math.log(abs((f3 - f2) / (f2 - f1)))) / math.log(r)
    except (ValueError, ZeroDivisionError):
      p = 2.0  # theoretical order for C3D10 quadratic elements

    # Richardson extrapolation to zero grid spacing
    f_extrapolated = f1 + (f1 - f2) / (r**p - 1.0)

    # Relative errors
    e_a21 = abs((f1 - f2) / f1)
    gci_fine = (safety_factor * e_a21) / (r**p - 1.0) * 100.0

    return {
        "apparent_order_p": p,
        "extrapolated_value": f_extrapolated,
        "relative_error_pct": e_a21 * 100.0,
        "gci_fine_pct": gci_fine,
        "is_converged": gci_fine < 2.0,  # ASME criterion < 2%
    }


if __name__ == "__main__":
  print("Open-FEA Mesh Optimizer Pipeline Initialized.")
  pipeline = FEAPipeline()
  # Sample 3-mesh convergence benchmark
  mesh_study = [
      SimulationResult(
          0.8, 142000, 89000, 20.8, 1.82, 45.2
      ),  # Fine (0.8 mm local)
      SimulationResult(
          1.2, 78000, 48000, 20.3, 1.84, 18.4
      ),  # Medium (1.2 mm local)
      SimulationResult(
          1.8, 38000, 22000, 19.4, 1.89, 6.1
      ),  # Coarse (1.8 mm local)
  ]
  gci_report = pipeline.calculate_gci(mesh_study)
  print(
      f"ASME V&V 20 Grid Convergence Index: {gci_report['gci_fine_pct']:.2f}%"
  )
  print(f"Convergence Verification Passed: {gci_report['is_converged']}")
